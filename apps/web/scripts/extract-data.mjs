// Pulls every figure the presentation shows out of the repo's research and
// evidence files, so no number on screen is typed by hand.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '../../..');
const read = (p) => JSON.parse(readFileSync(resolve(repo, p), 'utf8'));
const L = (v) => (typeof v === 'string' ? JSON.parse(v) : v);

const viz = read('docs/research-story/visualizations.json');
const chart = Object.fromEntries(viz.charts.map((c) => [c.chart_id, c]));

const categories = L(chart.openai_math_categories.records).map((r) => ({
  name: r.category,
  n: r.manuscripts,
}));
const cryptoSubset = L(chart.openai_crypto_subset.records).map((r) => ({
  relevance: r.relevance,
  n: r.manuscripts,
}));
const hist = L(chart.historical_publication_trend.records).filter((r) => r.subject === 'fission_title');
const fission = hist
  .filter((r) => r.year >= 1935 && r.year <= 1947)
  .map((r) => ({ year: r.year, count: r.count, total: r.denominator_count, share: r.share }));
const journalRecords = hist.reduce((s, r) => s + r.denominator_count, 0);
const histYears = [Math.min(...hist.map((r) => r.year)), Math.max(...hist.map((r) => r.year))];
const priorWork = L(chart.prior_work_timeline.records).map((r) => ({
  name: r.name,
  org: r.organization,
  category: r.category,
  description: r.description.replace(/([a-z])([A-Z][a-z])/g, '$1 $2'),
  url: r.original_url,
  date: r.source_date,
  status: r.status,
  relation: r.relationship_to_bunker.replace('custody demo', 'Bunker custody'),
}));

const wd = read('artifacts/devnet-transactions/v1-live-20261012-xmss-withdraw-sol.json');
const rot = read('artifacts/devnet-transactions/v1-live-20261012-xmss-rotate-root.json');
const pub = read('artifacts/public-deployment.json');

const out = {
  _source: 'generated by scripts/extract-data.mjs; do not edit by hand',
  manuscripts: categories.reduce((s, c) => s + c.n, 0),
  categories,
  cryptoSubset,
  fission,
  journalRecords,
  histYears,
  priorWork,
  withdrawal: {
    signature: wd.transaction_signature,
    slot: wd.network_transaction.slot,
    blockTime: wd.network_transaction.blockTime,
    version: wd.network_transaction.version,
    bytes: wd.transaction_bytes,
    cu: wd.network_transaction.meta.computeUnitsConsumed,
    cuLimit: wd.inline_resources.compute_unit_limit,
    fee: wd.network_transaction.meta.fee,
    witnessBytes: wd.witness_bytes,
    success: wd.success === true && wd.network_transaction.meta.err === null,
    logs: wd.network_transaction.meta.logMessages,
    treasury: wd.before.treasury,
    tokenAccount: wd.before.token_source,
    recipient: pub.vaults.find((v) => v.mode === 'xmss').recipient_sol,
    amountLamports: Math.max(...wd.network_transaction.meta.postBalances.map((p, i) => p - wd.network_transaction.meta.preBalances[i])),
  },
  rotation: {
    signature: rot.transaction_signature,
    slot: rot.slot ?? rot.network_transaction?.slot,
    bytes: rot.transaction_bytes,
    cu: rot.network_transaction?.meta?.computeUnitsConsumed ?? rot.compute_units,
    consumedBefore: rot.before.consumed,
    epochBefore: rot.before.epoch,
  },
  program: { id: pub.program_id, binaryBytes: pub.program_binary_bytes, cluster: pub.cluster },
  /** every confirmed devnet operation that matters for the proof grid (slide 9) */
  proofOps: [
    ['array-withdraw-sol', 'array withdraw SOL'],
    ['array-withdraw-mock-usdc', 'array withdraw mock USDC'],
    ['merkle-withdraw-sol', 'Merkle withdraw SOL'],
    ['merkle-withdraw-mock-usdc', 'Merkle withdraw mock USDC'],
    ['xmss-withdraw-sol', 'XMSS withdraw SOL'],
    ['xmss-withdraw-mock-usdc', 'XMSS withdraw mock USDC'],
    ['xmss-burn-leaves', 'XMSS burn leaves'],
    ['xmss-rotate-root', 'XMSS rotate root'],
    ['xmss-post-rotation-withdraw-sol', 'post-rotation withdraw SOL'],
    ['xmss-post-rotation-withdraw-mock-usdc', 'post-rotation withdraw mock USDC'],
  ].map(([op, label]) => {
    const t = pub.confirmed_transactions.find((x) => x.operation === `v1-live-20261012-${op}`);
    if (!t || t.success !== true) throw new Error(`missing confirmed op ${op}`);
    return { label, signature: t.transaction_signature };
  }),
  /** the confirmed devnet XMSS operations, in order */
  xmssOps: [
    ['withdraw-sol', 'withdraw SOL'],
    ['withdraw-mock-usdc', 'withdraw mock USDC'],
    ['burn-leaves', 'burn leaves'],
    ['rotate-root', 'rotate root'],
    ['post-rotation-withdraw-sol', 'post-rotation withdraw SOL'],
    ['post-rotation-withdraw-mock-usdc', 'post-rotation withdraw mock USDC'],
  ].map(([op, label]) => {
    const t = pub.confirmed_transactions.find((x) => x.operation === `v1-live-20261012-xmss-${op}`);
    if (!t || t.success !== true) throw new Error(`missing confirmed xmss op ${op}`);
    return { label, signature: t.transaction_signature, bytes: t.transaction_bytes, cu: t.compute_units };
  }),
};
writeFileSync(resolve(here, '../src/data/story.json'), JSON.stringify(out, null, 1) + '\n');
console.log('story.json:', out.manuscripts, 'manuscripts,', out.journalRecords, 'journal records, slot', out.withdrawal.slot);
